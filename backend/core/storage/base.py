"""
core/storage/base.py
======================
Abstract repository interfaces for the storage layer.

Every repository works with plain `dict` payloads rather than agent
pydantic models - this keeps `core/` fully decoupled from agent
packages (core never imports from an agent, agents convert their own
schema objects to/from dicts at the storage boundary).

Three repositories are defined, matching what the agents actually need:
- `ActionRepository`: CRUD for tracked action items (Action Tracker
  agent).
- `BriefRepository`: store/retrieve the latest generated pre-meet brief
  per meeting (Calendar & Meeting agent).
- `SummaryRepository`: store/retrieve generated email/thread summaries
  (Email & Summary agent produces these; Action Tracker agent reads
  them via `agent_email.service`, never by touching this repository
  directly - see agent_action_tracker/service.py).

`StorageBackend` bundles all three repositories together so agents only
need a single import (`core.storage.factory.get_storage()`) to reach
whichever repository they need.
"""

from abc import ABC, abstractmethod
from typing import Any, Optional


class ActionRepository(ABC):
    """CRUD operations for tracked action items."""

    @abstractmethod
    async def add(self, action: dict[str, Any]) -> dict[str, Any]:
        """Persist a new action item. `action` must include a unique 'id' key."""

    @abstractmethod
    async def get(self, action_id: str) -> Optional[dict[str, Any]]:
        """Return the action item with the given id, or None if not found."""

    @abstractmethod
    async def list(self, filters: Optional[dict[str, Any]] = None) -> list[dict[str, Any]]:
        """
        Return all action items, optionally filtered by exact-match on
        the given dict of field -> value pairs (e.g. {"status": "Overdue"}).
        """

    @abstractmethod
    async def update(self, action_id: str, patch: dict[str, Any]) -> Optional[dict[str, Any]]:
        """Apply a partial update to an existing action item; returns the updated record, or None if not found."""


class BriefRepository(ABC):
    """Store/retrieve pre-meet briefs generated by the Calendar & Meeting agent."""

    @abstractmethod
    async def save_brief(self, meeting_id: str, brief: dict[str, Any]) -> dict[str, Any]:
        """Persist (or overwrite) the latest brief for a given meeting id."""

    @abstractmethod
    async def get_latest_brief(self, meeting_id: str) -> Optional[dict[str, Any]]:
        """Return the most recently saved brief for a meeting id, or None if none exists."""


class SummaryRepository(ABC):
    """Store/retrieve email/thread summaries generated by the Email & Summary agent."""

    @abstractmethod
    async def save_summary(self, thread_id: str, summary: dict[str, Any]) -> dict[str, Any]:
        """Persist (or overwrite) the latest summary for a given thread/meeting id."""

    @abstractmethod
    async def get_latest_summary(self, thread_id: str) -> Optional[dict[str, Any]]:
        """Return the most recently saved summary for a thread/meeting id, or None if none exists."""

    @abstractmethod
    async def list_summaries(self, filters: Optional[dict[str, Any]] = None) -> list[dict[str, Any]]:
        """Return all stored summaries, optionally filtered by exact-match field values."""


class StorageBackend(ABC):
    """
    Bundles the three repositories behind a single object so agents can
    do `get_storage().actions.add(...)` / `.briefs.get_latest_brief(...)`
    / `.summaries.save_summary(...)` without separate imports per
    repository.
    """

    actions: ActionRepository
    briefs: BriefRepository
    summaries: SummaryRepository
