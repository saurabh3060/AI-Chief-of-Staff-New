"""
agent_email/prompts_common.py
=============================
Shared helpers for the email agent's prompt builders/parsers:

* meeting-invite boilerplate stripping,
* tolerant LLM-JSON sanitize/repair,
* output quality-filter regexes + filters,
* value sanitisation and action-item normalisation.

Both the single-email summariser prompts (``agent_email/prompts.py``) and
the cluster-synthesis prompts (``agent_email/prompts_cluster.py``) import
from here so the regexes and JSON repair logic live in exactly one place.
"""

import json
import re


# ---------------------------------------------------------------------------
# Meeting-invite boilerplate stripping
# ---------------------------------------------------------------------------

# Matches whole lines that are pure meeting-invite/dial-in boilerplate
# generated by Teams/Webex/Outlook ("Meeting ID: ...", "Passcode: ...",
# "Join on a video conferencing device", "For organizers: Meeting
# options", a dial-in phone number line, a video ID line, etc.). Applied
# BEFORE the email body ever reaches the LLM.
_MEETING_BOILERPLATE_LINE_RE = re.compile(
    r"^\s*("
    r"microsoft teams meeting"
    r"|join (on|the) (a )?(video conferencing device|meeting now)"
    r"|meeting id\s*:?.*"
    r"|passcode\s*:?.*"
    r"|video id\s*:?.*"
    r"|dial[- ]?in.*"
    r"|phone conference id.*"
    r"|find a local number.*"
    r"|for organizers\s*:.*"
    r"|meeting options.*"
    r"|\+?\d[\d ()-]{7,}\d\s*,,.*"  # dial-in number lines often end in ",,<conf id>#"
    r"|_{5,}\s*$"  # the long underscore divider Outlook inserts around invite blocks
    r")\s*$",
    re.IGNORECASE,
)


def strip_meeting_boilerplate(body_text: str) -> str:
    """
    Remove Teams/Webex/Outlook meeting-invite logistics lines (meeting ID,
    passcode, dial-in numbers, "join on a video conferencing device",
    organizer options, etc.) from an email body before it is handed to the
    LLM, so that boilerplate can never be quoted/paraphrased into a summary
    bullet, action item, or question. Lines that don't match this specific
    boilerplate shape are left completely untouched.
    """
    kept_lines = [line for line in body_text.splitlines() if not _MEETING_BOILERPLATE_LINE_RE.match(line)]
    collapsed = re.sub(r"\n{3,}", "\n\n", "\n".join(kept_lines))
    return collapsed.strip()


# ---------------------------------------------------------------------------
# Output quality-filter regexes (shared by both prompt families)
# ---------------------------------------------------------------------------

_NON_EXECUTIVE_SUMMARY_RE = re.compile(
    r"^\s*(this\s+(email|message|mail)|the\s+(email|message|mail))\b.*\b"
    r"(summarizes|states|stated|mentions|indicates|discusses|contains|is\s+about|is\s+a\s+follow.?up|pertains)",
    re.IGNORECASE,
)

_PURE_MEETING_INVITE_PLACEHOLDER_RE = re.compile(
    r"^\s*(this\s+(is|email|message)|the\s+(email|message))\b.*\b"
    r"(meeting\s+invite|calendar\s+invite|invite(\s+with)?|logistics\s+email)\b.*\b"
    r"(no\s+(further|additional|other|real)\s+(content|discussion|information|details)|"
    r"nothing\s+(else|further)|no\s+substantive)",
    re.IGNORECASE,
)

_PROCESS_META_SUMMARY_RE = re.compile(
    r"the explanation given is|"
    r"the explanation provided (by|is)|"
    r"there is a challenge to the explanation|"
    r"the pending decision is|"
    r"current position is that|"
    r"the timeline is not yet met|"
    r"the operational blocker is|"
    r"owner'?s overdue view|"
    r"lack of transparency",
    re.IGNORECASE,
)

_NON_ACTION_RE = re.compile(
    r"^\s*(join|attend|be\s+available\s+for|prepare\s+for)\b.*\bmeeting\b"
    r"|\bmeeting\s+id\b|\bpasscode\b|\bdial[- ]?in\b",
    re.IGNORECASE,
)

_NON_EXECUTIVE_QUESTION_RE = re.compile(
    r"purpose\s+of\s+(this|the)\s+(meeting|email)\b"
    r"|specific\s+topic\s+being\s+discussed"
    r"|expected\s+outcome\s+of\s+the\s+meeting"
    r"|^\s*what\s+are\s+the\s+risks\??\s*$"
    r"|^\s*what\s+is\s+the\s+timeline\??\s*$"
    r"|^\s*what\s+is\s+the\s+current\b"
    r"|^\s*how\s+do\s+we\s+manage\b"
    r"|^\s*what\s+are\s+the\s+implications\b"
    r"|^\s*(can|will|could|should)\s+(the\s+)?ceo\b"
    r"|confirm the target"
    r"|industry benchmarks",
    re.IGNORECASE,
)

_MEETING_LOGISTICS_LEAK_RE = re.compile(
    r"\bmeeting\s*id\b|\bpasscode\b|\bdial[- ]?in\b|\bvideo\s*id\b|\bconference\s*id\b",
    re.IGNORECASE,
)

_PLACEHOLDER_FIGURE_RE = re.compile(
    r"(?:₹|rs\.?)\s*[xy]\b"
    r"|\b[xy]\s*(?:cr|crore|days|bps)\b"
    r"|\bfrom\s+(?:₹|rs\.?)?\s*[xy]\b",
    re.IGNORECASE,
)

_SPECULATION_RE = re.compile(
    r"\b(probably|possibly|perhaps|presumably|it appears|appears to|seems to|seems that|"
    r"might have|may have been|likely that)\b",
    re.IGNORECASE,
)


def dedupe_preserving_order(items: list[str]) -> list[str]:
    """Remove case/whitespace-insensitive duplicates, keeping first occurrence's text."""
    seen: set[str] = set()
    out: list[str] = []
    for item in items:
        key = re.sub(r"\s+", " ", item.strip().lower())
        if key and key not in seen:
            seen.add(key)
            out.append(item)
    return out


def is_low_confidence_text(item: str) -> bool:
    """True when the model hedged instead of stating a source-backed fact."""
    return bool(_SPECULATION_RE.search(item) or _PLACEHOLDER_FIGURE_RE.search(item))


def quality_filter_summary(items: list[str]) -> list[str]:
    """Drop document-meta/placeholder/speculative/pure-meeting-invite bullets; keep at most 5."""
    filtered = [
        item for item in items
        if not _NON_EXECUTIVE_SUMMARY_RE.search(item)
        and not _PROCESS_META_SUMMARY_RE.search(item)
        and not _PURE_MEETING_INVITE_PLACEHOLDER_RE.search(item)
        and not _MEETING_LOGISTICS_LEAK_RE.search(item)
        and not is_low_confidence_text(item)
    ]
    return dedupe_preserving_order(filtered)[:5]


def quality_filter_actions(items: list[str]) -> list[str]:
    """Drop meeting-logistics-only and speculative action items. No count cap."""
    filtered = [
        item for item in items
        if not _NON_ACTION_RE.search(item) and not is_low_confidence_text(item)
    ]
    return dedupe_preserving_order(filtered)


def quality_filter_questions(items: list[str]) -> list[str]:
    """Drop generic/placeholder/speculative/logistics-leak questions; keep at most 6."""
    filtered = [
        item for item in items
        if not _NON_EXECUTIVE_QUESTION_RE.search(item)
        and not _MEETING_LOGISTICS_LEAK_RE.search(item)
        and not is_low_confidence_text(item)
    ]
    return dedupe_preserving_order(filtered)[:6]


# ---------------------------------------------------------------------------
# Tolerant LLM-JSON sanitize / repair
# ---------------------------------------------------------------------------

_JSON_STRING_ESCAPES = {"\n": "\\n", "\r": "\\r", "\t": "\\t"}


def sanitize_llm_json_text(text: str) -> str:
    """
    Escape raw control characters that appear *inside* JSON string literals
    in a raw LLM response, so ``json.loads`` doesn't choke on a literal
    newline/tab typed inside a string value. Control characters OUTSIDE
    strings are left untouched.
    """
    out: list[str] = []
    in_string = False
    escaped = False
    for ch in text:
        if in_string:
            if escaped:
                out.append(ch)
                escaped = False
                continue
            if ch == "\\":
                out.append(ch)
                escaped = True
                continue
            if ch == '"':
                out.append(ch)
                in_string = False
                continue
            if ch in _JSON_STRING_ESCAPES:
                out.append(_JSON_STRING_ESCAPES[ch])
                continue
            if ord(ch) < 0x20:
                continue
            out.append(ch)
        else:
            if ch == '"':
                in_string = True
            out.append(ch)
    return "".join(out)


def repair_llm_json_text(text: str) -> str:
    """
    Conservatively repair the structural JSON slips small models produce
    (unescaped inner quotes, trailing commas, missing commas between
    adjacent elements, unbalanced trailing brackets). Runs ONLY after a
    plain ``json.loads`` has already failed.
    """
    # --- Step 1: escape stray inner double-quotes ---
    out: list[str] = []
    in_string = False
    escaped = False
    n = len(text)
    for i, ch in enumerate(text):
        if in_string:
            if escaped:
                out.append(ch)
                escaped = False
                continue
            if ch == "\\":
                out.append(ch)
                escaped = True
                continue
            if ch == '"':
                j = i + 1
                while j < n and text[j] in " \t\r\n":
                    j += 1
                nxt = text[j] if j < n else ""
                if nxt in (",", "}", "]", ":", ""):
                    out.append(ch)
                    in_string = False
                else:
                    out.append('\\"')
                continue
            out.append(ch)
        else:
            if ch == '"':
                in_string = True
            out.append(ch)
    repaired = "".join(out)

    # --- Step 2: strip trailing commas before ] or } ---
    repaired = re.sub(r",(\s*[\]}])", r"\1", repaired)

    # --- Step 3: insert missing commas between adjacent elements ---
    # `[^\S\n]*\n\s*` = whitespace that contains a newline, without the overlapping \s*\n\s*
    # ambiguity (py/polynomial-redos).
    repaired = re.sub(r'"([^\S\n]*\n\s*)"', r'",\1"', repaired)
    repaired = re.sub(r'\}([^\S\n]*\n\s*)\{', r'},\1{', repaired)
    repaired = re.sub(r'"([^\S\n]*\n\s*)\{', r'",\1{', repaired)

    # --- Step 4: balance trailing brackets ---
    stack: list[str] = []
    in_string = False
    escaped = False
    for ch in repaired:
        if in_string:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_string = False
            continue
        if ch == '"':
            in_string = True
        elif ch in "[{":
            stack.append(ch)
        elif ch == "]":
            if stack and stack[-1] == "[":
                stack.pop()
        elif ch == "}":
            if stack and stack[-1] == "{":
                stack.pop()
    for opener in reversed(stack):
        repaired += "]" if opener == "[" else "}"

    return repaired


# ---------------------------------------------------------------------------
# Value sanitisation + action-item normalisation
# ---------------------------------------------------------------------------

_STRAY_CONTROL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f\ufeff\ufffd]")

_PLACEHOLDER_WORDS = ("Owner", "Action", "Deadline", "Deadline or TBD")
_LITERAL_PLACEHOLDER_RE = re.compile(
    r"\[\s*(?:" + "|".join(re.escape(w) for w in _PLACEHOLDER_WORDS) + r")\s*\]",
    re.IGNORECASE,
)
_ONLY_PUNCTUATION_RE = re.compile(r"^[\s:\-–—.]*$")


def _unwrap_literal_placeholders(value: str) -> str:
    """Replace literal '[Owner]'/'[Action]'/'[Deadline...]' tokens with a plain fallback word."""
    def _replace(match: "re.Match[str]") -> str:
        word = match.group(0).strip("[] ").lower()
        if word.startswith("deadline"):
            return "TBD"
        if word == "owner":
            return "Unassigned"
        return ""

    return _LITERAL_PLACEHOLDER_RE.sub(_replace, value)


def sanitize_text_value(value: str, *, allow_newlines: bool = False) -> str:
    """
    Clean a single string value extracted from parsed LLM JSON (a summary
    bullet, action item, or question) of stray control/non-printable
    characters, without touching real content.
    """
    if not allow_newlines:
        value = re.sub(r"[\r\n\t]+", " ", value)
    cleaned = _STRAY_CONTROL_RE.sub("", value)
    cleaned = _unwrap_literal_placeholders(cleaned)
    return re.sub(r"[ \t]{2,}", " ", cleaned).strip()


def sanitize_and_drop_empty(items: list) -> list[str]:
    """Sanitize each raw item and drop any that end up empty or pure separator punctuation."""
    cleaned = [sanitize_text_value(str(item)) for item in items if str(item).strip()]
    return [c for c in cleaned if c and not _ONLY_PUNCTUATION_RE.match(c)]


def sanitize_and_normalize_action_items(raw_items: list) -> list[str]:
    """
    Normalize the model's `action_items` array into the flat
    "<owner>: <task> - <due_date>" string format every downstream consumer
    expects, accepting either the structured dict shape or a plain string.
    """
    normalized: list[str] = []
    for raw_item in raw_items:
        if isinstance(raw_item, dict):
            text = sanitize_text_value(str(raw_item.get("text", "")))
            if not text or _ONLY_PUNCTUATION_RE.match(text):
                continue
            due_date_raw = raw_item.get("due_date")
            due_date = sanitize_text_value(str(due_date_raw)) if due_date_raw else ""
            due_date = due_date if due_date and due_date.lower() != "null" else "TBD"
            status_raw = str(raw_item.get("status", "")).strip().lower()
            if status_raw == "done":
                text = f"{text} [done]"
            normalized.append(f"{text} - {due_date}")
        else:
            text = sanitize_text_value(str(raw_item))
            if text and not _ONLY_PUNCTUATION_RE.match(text):
                normalized.append(text)
    return normalized
